"""## Funcion de destilación"""

def distillation_loss(student_logits, teacher_probs, true_labels, T=4, alpha=0.7):
    log_probs = F.log_softmax(student_logits / T, dim=1)
    teacher_probs = teacher_probs.detach()
    loss_kd = F.kl_div(log_probs, teacher_probs, reduction='batchmean') * (T * T)
    loss_ce = F.cross_entropy(student_logits, true_labels)
    return alpha * loss_kd + (1 - alpha) * loss_ce

"""## Propuesta de modelo estudiante"""

class SmallResNet18(nn.Module):
    def __init__(self, num_classes):
        super(SmallResNet18, self).__init__()
        self.base = models.resnet18(weights=None)

        self.base.conv1 = nn.Conv2d(3, 64, kernel_size=3, stride=1, padding=1, bias=False)
        self.base.maxpool = nn.Identity()
        self.base.fc = nn.Linear(self.base.fc.in_features, num_classes)

    def forward(self, x):
        return self.base(x)

"""## Entrenamiento"""

