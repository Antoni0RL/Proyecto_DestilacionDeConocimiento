    student.train()
    total_loss = 0
    correct = 0
    total = 0

    for imgs, labels in train_loader:
        imgs, labels = imgs.to(device), labels.squeeze().long().to(device)

        with torch.no_grad():
            logits18 = model(imgs)
            logits50 = model2(imgs)
            soft18 = F.softmax(logits18 / T, dim=1)
            soft50 = F.softmax(logits50 / T, dim=1)

            conf18 = soft18[torch.arange(len(labels)), labels]
            conf50 = soft50[torch.arange(len(labels)), labels]
            mask = conf18 > conf50
            best_softs = soft18.clone()
            best_softs[~mask] = soft50[~mask]

        optimizer.zero_grad()
        student_logits = student(imgs)
        loss = distillation_loss(student_logits, best_softs, labels, T=T, alpha=alpha)
        loss.backward()
        optimizer.step()

        total_loss += loss.item()
        preds = torch.argmax(student_logits, dim=1)
        correct += (preds == labels).sum().item()
        total += labels.size(0)

    train_acc = correct / total
    train_loss_list.append(total_loss)
    train_acc_list_ST.append(train_acc)

    # Validación
    student.eval()
    correct_val = 0
    total_val = 0
    with torch.no_grad():
        for imgs, labels in val_loader:
            imgs, labels = imgs.to(device), labels.squeeze().long().to(device)
