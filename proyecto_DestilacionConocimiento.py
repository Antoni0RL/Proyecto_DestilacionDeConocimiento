def obtener_logits(modelo, dataloader, device, nombre_modelo="resnet18"):
    modelo = modelo.to(device)
    modelo.eval()

    all_logits = []
    all_labels = []

    with torch.no_grad():
        for imgs, labels in dataloader:
            imgs = imgs.to(device)
            logits = modelo(imgs).cpu()  # Pasa a CPU inmediatamente
            all_logits.append(logits)
            all_labels.append(labels)  # Útil si los necesitas después

    # Concatenar todos los logits
    logits_tensor = torch.cat(all_logits)
    labels_tensor = torch.cat(all_labels)

    # Guardar en disco
    os.makedirs("logits", exist_ok=True)
    torch.save(logits_tensor, f"logits/{nombre_modelo}_logits.pt")
    torch.save(labels_tensor, f"logits/{nombre_modelo}_labels.pt")

    print(f"Logits de {nombre_modelo} guardados correctamente.")
    return logits_tensor, labels_tensor

